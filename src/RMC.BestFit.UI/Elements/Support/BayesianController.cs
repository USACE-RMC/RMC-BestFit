        /// <summary>
        /// Creates the default Markov chain trace plot.
        /// </summary>
        /// <returns>A new plot configured for displaying MCMC trace evolution.</returns>
        /// <remarks>
        /// Y-axis title is left empty — the App control binds it to the selected parameter name.
        /// X-axis is fixed at "Evolution" with integer formatting.
        /// Axis keys "Yaxis"/"Xaxis" match the existing XAML convention.
        /// </remarks>
        private static Plot CreateDefaultMarkovChainTracePlot()
        {
            var plot = new Plot();
            ApplyDefaultPlotStyle(plot);

            // MCMC trace plots draw 20 thin chain lines simultaneously. WPF's anti-aliased
            // stroke tessellation is the dominant render-thread cost for that many concurrent
            // line geometries; disabling it on this plot trades a barely-visible edge softness
            // for a multi-x speedup on wheel zoom, pan, and zoom-extents.
            plot.DisableShapeAntiAliasing = true;

            // Cache the rasterized plot output so the WPF compositor reuses the cached bitmap
            // while the user drags a transient overlay (e.g., the magnifier-glass zoom
            // rectangle) over the plot. Without the cache, WPF re-rasterizes the plot's
            // 20 chain geometries under the dirty region on every compositor frame during
            // the drag, producing visible multi-second drag lag. The cache regenerates on
            // every Plot.InvalidatePlot — i.e., real plot changes — so wheel/pan/zoom-extents
            // see the same fresh content.
            plot.UseBitmapCache = true;

            plot.Axes.Add(new LinearAxis
            {
                Name = "YAxis",
                Key = "Yaxis",
                Position = OxyPlot.Axes.AxisPosition.Left,
                Title = "",
                AxisTitleDistance = 20,
                TitleFontSize = 16,
                FontSize = 12
            });
            plot.Axes.Add(new LinearAxis
            {
                Name = "XAxis",
                Key = "Xaxis",
                Position = OxyPlot.Axes.AxisPosition.Bottom,
                Title = "Iteration",
                AxisTitleDistance = 20,
                TitleFontSize = 16,
                FontSize = 12,
                StringFormat = "N0"
            });

            return plot;
        }

        /// <summary>
        /// Creates the default posterior histogram plot.
        /// </summary>
        /// <returns>A new plot configured for displaying posterior parameter histograms.</returns>
        /// <remarks>
        /// Y-axis shows density with scientific notation.
        /// X-axis title is left empty — the App control binds it to the selected parameter name.
        /// </remarks>
