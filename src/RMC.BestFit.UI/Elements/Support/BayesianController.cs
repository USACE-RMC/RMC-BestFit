        /// <summary>
        /// Applies the standard default plot style shared by all Bayesian diagnostic plots.
        /// </summary>
        /// <param name="plot">The plot to style.</param>
        /// <remarks>
        /// Sets transparent background, white plot area, dark gray legend border, and standard padding.
        /// Matches the XAML defaults from the Bayesian control templates.
        /// </remarks>
        private static void ApplyDefaultPlotStyle(Plot plot)
        {
            plot.BorderThickness = new Thickness(0);
            plot.Background = Brushes.Transparent;
            plot.LegendBackground = ColorFromHex("#8CFFFFFF");
            plot.LegendBorder = Colors.DarkGray;
            plot.LegendPosition = OxyPlot.Legends.LegendPosition.TopRight;
            plot.Padding = new Thickness(10, 10, 14, 10);
            plot.PlotAreaBackground = new SolidColorBrush(Colors.White);
        }

