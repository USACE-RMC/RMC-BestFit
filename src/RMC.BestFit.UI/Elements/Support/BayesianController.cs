        /// <summary>
        /// Sets up undo bridges for all 7 diagnostic plots and BayesianAnalysis conditional undo recording.
        /// </summary>
        /// <param name="getUndo">Lambda returning the <see cref="IUndoManager"/> when undo is enabled, or null.</param>
        /// <param name="target">The owning element, used as the undo action target.</param>
        /// <param name="onRecorded">Callback invoked when any bridge records an undo action (typically <c>SetIsDirty(true)</c>).</param>
        /// <param name="bayesianAnalysis">The <see cref="BayesianAnalysis"/> instance to monitor for property changes. May be null.</param>
        /// <param name="onValidate">Callback invoked after Bayesian settings changes require element validation.</param>
        /// <remarks>
        /// Called by the owning element after construction and after Open()/Copy().
        /// Disposes any existing bridges before creating new ones.
        /// </remarks>
        public void SetupBridges(Func<IUndoManager> getUndo, object target, Action onRecorded,
            BayesianAnalysis bayesianAnalysis = null, Action onValidate = null)
        {
            if (_isDisposed)
                throw new ObjectDisposedException(nameof(BayesianController),
                    "Cannot rebuild bridges on a disposed BayesianController. Recreate the controller " +
                    "via the owning element if bridges need to be re-established after Dispose().");
            DisposeBridges();
            _getUndo = getUndo;
            _onRecorded = onRecorded;
            _target = target;
            _onValidate = onValidate;

            if (_markovChainTracePlot != null)
                _markovChainTracePlotUndo = new PlotUndoManager(_markovChainTracePlot, getUndo, "MCMC trace plot", target, onRecorded);
            if (_histogramPlot != null)
                _histogramPlotUndo = new PlotUndoManager(_histogramPlot, getUndo, "histogram plot", target, onRecorded);
            if (_kernelDensityPlot != null)
                _kernelDensityPlotUndo = new PlotUndoManager(_kernelDensityPlot, getUndo, "kernel density plot", target, onRecorded);
            if (_autocorrelationPlot != null)
                _autocorrelationPlotUndo = new PlotUndoManager(_autocorrelationPlot, getUndo, "autocorrelation plot", target, onRecorded);
            if (_meanLikelihoodPlot != null)
                _meanLikelihoodPlotUndo = new PlotUndoManager(_meanLikelihoodPlot, getUndo, "mean likelihood plot", target, onRecorded);
            if (_bivariateHeatMapPlot != null)
                _bivariateHeatMapPlotUndo = new PlotUndoManager(_bivariateHeatMapPlot, getUndo, "bivariate heat map plot", target, onRecorded);
            if (_influenceDiagnosticsPlot != null)
                _influenceDiagnosticsPlotUndo = new PlotUndoManager(_influenceDiagnosticsPlot, getUndo, "influence diagnostics plot", target, onRecorded);

            // BayesianAnalysis undo bridges
            SetupBayesianBridges(bayesianAnalysis);
        }

        /// <summary>
        /// Disposes all undo bridges for the 7 diagnostic plots.
        /// </summary>
        /// <remarks>
        /// Called before creating new bridges in <see cref="SetupBridges"/> and during <see cref="Dispose"/>.
        /// Safe to call multiple times.
        /// </remarks>
        public void DisposeBridges()
        {
            DisposeBayesianBridges();

            _markovChainTracePlotUndo?.Dispose();
            _markovChainTracePlotUndo = null;
            _histogramPlotUndo?.Dispose();
            _histogramPlotUndo = null;
            _kernelDensityPlotUndo?.Dispose();
            _kernelDensityPlotUndo = null;
            _autocorrelationPlotUndo?.Dispose();
            _autocorrelationPlotUndo = null;
            _meanLikelihoodPlotUndo?.Dispose();
            _meanLikelihoodPlotUndo = null;
            _bivariateHeatMapPlotUndo?.Dispose();
            _bivariateHeatMapPlotUndo = null;
            _influenceDiagnosticsPlotUndo?.Dispose();
            _influenceDiagnosticsPlotUndo = null;
        }

        /// <summary>
        /// Suspends undo recording for all 7 diagnostic plot undo managers.
        /// </summary>
        /// <returns>An <see cref="IDisposable"/> that resumes recording when disposed.</returns>
        /// <remarks>
        /// Use this when performing bulk plot operations (e.g., clearing and adding data series)
        /// that should not be recorded as individual undo actions. After disposing the returned token,
        /// call <see cref="RebuildSeriesAndAnnotationBridges"/> to reconnect bridges.
        /// </remarks>
        public IDisposable SuspendPlotBridges()
        {
            var suspensions = new List<IDisposable>();
            if (_markovChainTracePlotUndo != null) suspensions.Add(_markovChainTracePlotUndo.SuspendRecording());
            if (_histogramPlotUndo != null) suspensions.Add(_histogramPlotUndo.SuspendRecording());
            if (_kernelDensityPlotUndo != null) suspensions.Add(_kernelDensityPlotUndo.SuspendRecording());
            if (_autocorrelationPlotUndo != null) suspensions.Add(_autocorrelationPlotUndo.SuspendRecording());
            if (_meanLikelihoodPlotUndo != null) suspensions.Add(_meanLikelihoodPlotUndo.SuspendRecording());
            if (_bivariateHeatMapPlotUndo != null) suspensions.Add(_bivariateHeatMapPlotUndo.SuspendRecording());
            if (_influenceDiagnosticsPlotUndo != null) suspensions.Add(_influenceDiagnosticsPlotUndo.SuspendRecording());

            // BA bridges are NOT suspended here — plot updates are unrelated to BA property recording.
            // BA bridges are only managed by SetupBridges/DisposeBridges lifecycle.

            return new AggregateDisposable(suspensions);
        }

        /// <summary>
        /// Rebuilds the series and annotation bridges for the specified plot.
        /// </summary>
        /// <param name="plot">The plot whose bridges need rebuilding after series/annotation changes.</param>
        /// <remarks>
        /// Call this after UpdateXxxPlot() methods that clear and repopulate
        /// <see cref="Plot.Series"/> and <see cref="Plot.Annotations"/>.
        /// Returns silently if the plot is not one of the 6 managed plots.
        /// </remarks>
        public void RebuildSeriesAndAnnotationBridges(Plot plot)
        {
            FindPlotUndoManager(plot)?.RebuildSeriesAndAnnotationBridges();
        }

        /// <summary>
        /// Finds the <see cref="PlotUndoManager"/> associated with the specified plot.
        /// </summary>
        /// <param name="plot">The plot to find the manager for.</param>
        /// <returns>The associated <see cref="PlotUndoManager"/>, or null if not found.</returns>
        private PlotUndoManager FindPlotUndoManager(Plot plot)
        {
            if (plot == _markovChainTracePlot) return _markovChainTracePlotUndo;
            if (plot == _histogramPlot) return _histogramPlotUndo;
            if (plot == _kernelDensityPlot) return _kernelDensityPlotUndo;
            if (plot == _autocorrelationPlot) return _autocorrelationPlotUndo;
            if (plot == _meanLikelihoodPlot) return _meanLikelihoodPlotUndo;
            if (plot == _bivariateHeatMapPlot) return _bivariateHeatMapPlotUndo;
            if (plot == _influenceDiagnosticsPlot) return _influenceDiagnosticsPlotUndo;
            return null;
        }

