        #region IDisposable

        /// <summary>
        /// Releases all undo bridges managed by this instance.
        /// </summary>
        public void Dispose()
        {
            if (_isDisposed) return;
            _isDisposed = true;
            DisposeBridges();
        }

        #endregion

        #region BayesianAnalysis Undo Bridges

        /// <summary>
        /// Creates the three BayesianAnalysis undo bridges and subscribes to UseDefaults flag changes.
        /// </summary>
        /// <param name="ba">The <see cref="BayesianAnalysis"/> to bridge. May be null.</param>
        private void SetupBayesianBridges(BayesianAnalysis ba)
        {
            DisposeBayesianBridges();
            _subscribedBayesianAnalysis = ba;
            if (ba == null || _getUndo == null) return;

            // Always-record bridge: UseDefaults flags, Type, PointEstimator, CredibleIntervalWidth, OutputLength
            _bayesianAlwaysBridge = new UndoableStateBridge(
                ba, _getUndo, "Bayesian settings", _target,
                includedProperties: AlwaysRecordProperties,
                onActionRecorded: _onRecorded);

            // Simulation properties bridge — always alive to preserve baselines.
            // The getUndo lambda returns null when UseDefaults is true, so the bridge
            // tracks property changes internally but cannot push to the undo manager.
            _simulationUndoEnabled = !ba.UseSimulationDefaults;
            _simulationPropsBridge = new UndoableStateBridge(
                ba, () => _simulationUndoEnabled ? _getUndo() : null,
                "simulation options", _target,
                includedProperties: SimulationDefaultsProperties,
                onActionRecorded: _onRecorded);

            // Advanced properties bridge — same gating pattern.
            _advancedUndoEnabled = !ba.UseAdvancedSimulationDefaults;
            _advancedPropsBridge = new UndoableStateBridge(
                ba, () => _advancedUndoEnabled ? _getUndo() : null,
                "advanced simulation options", _target,
                includedProperties: AdvancedDefaultsProperties,
                onActionRecorded: _onRecorded);

            // Listen for UseDefaults flag changes to toggle the gating flags
            ba.PropertyChanged += BayesianAnalysis_UseDefaultsChanged;

        }

        /// <summary>
        /// Disposes all BayesianAnalysis bridges and unsubscribes from UseDefaults monitoring.
        /// </summary>
        private void DisposeBayesianBridges()
        {
            if (_subscribedBayesianAnalysis != null)
                _subscribedBayesianAnalysis.PropertyChanged -= BayesianAnalysis_UseDefaultsChanged;

            _bayesianAlwaysBridge?.Dispose();
            _bayesianAlwaysBridge = null;
            _simulationPropsBridge?.Dispose();
            _simulationPropsBridge = null;
            _advancedPropsBridge?.Dispose();
            _advancedPropsBridge = null;

            _subscribedBayesianAnalysis = null;
        }

        /// <summary>
        /// Handles UseDefaults flag changes to create or dispose the conditional simulation bridges.
        /// When UseDefaults goes true, the bridge is disposed so automatic property changes from
        /// <see cref="BayesianAnalysis.SetDefaultSimulationOptions"/> are NOT recorded.
        /// When UseDefaults goes false, a new bridge is created to record user edits.
        /// Also calls <see cref="_onValidate"/> for validation refresh on any BA property change.
        /// </summary>
        private void BayesianAnalysis_UseDefaultsChanged(object sender, PropertyChangedEventArgs e)
        {
            var ba = _subscribedBayesianAnalysis;
            if (ba == null) return;

            // Refresh validation on any BA property change (including during undo)
            _onValidate?.Invoke();

            if (e.PropertyName == nameof(BayesianAnalysis.UseSimulationDefaults))
            {
                _simulationUndoEnabled = !ba.UseSimulationDefaults;
            }
            else if (e.PropertyName == nameof(BayesianAnalysis.UseAdvancedSimulationDefaults))
            {
                _advancedUndoEnabled = !ba.UseAdvancedSimulationDefaults;
            }
        }

        #endregion

