        /// <summary>
        /// Copies all 7 diagnostic plot settings from this instance to a target instance.
        /// </summary>
        /// <param name="target">The target <see cref="BayesianController"/> to copy to.</param>
        /// <remarks>
        /// Uses <see cref="PlotSerializer"/> round-trip (ToXElement → FromXElement) to deep-copy
        /// all visual properties. Called by the owning element's Copy() method.
        /// </remarks>
        public void CopyTo(BayesianController target)
        {
            if (target == null) return;

            CopyPlot(_markovChainTracePlot, target._markovChainTracePlot);
            CopyPlot(_histogramPlot, target._histogramPlot);
            CopyPlot(_kernelDensityPlot, target._kernelDensityPlot);
            CopyPlot(_autocorrelationPlot, target._autocorrelationPlot);
            CopyPlot(_meanLikelihoodPlot, target._meanLikelihoodPlot);
            CopyPlot(_bivariateHeatMapPlot, target._bivariateHeatMapPlot);
            CopyPlot(_influenceDiagnosticsPlot, target._influenceDiagnosticsPlot);
        }

        /// <summary>
        /// Serializes a single plot's settings to the database.
        /// </summary>
        /// <param name="dtView">The database table view to write to.</param>
        /// <param name="rowIndex">The row index to write at.</param>
        /// <param name="columnName">The database column name.</param>
        /// <param name="plot">The plot to serialize.</param>
        private static void SerializePlot(DataTableView dtView, int rowIndex, string columnName, Plot plot)
        {
            // Guard against missing columns — mirrors DeserializePlot. Lets callers with a
            // narrower schema (e.g., B17CAnalysis, which persists only 4 of the 7 Bayesian
            // diagnostic plots) safely invoke Serialize() on the whole controller.
            if (!dtView.ColumnNames.Contains(columnName)) return;
            dtView.EditCell(rowIndex, columnName, plot != null ? PlotSerializer.ToXElement(plot).ToString() : "");
        }

        /// <summary>
        /// Deserializes a single plot's settings from the database with backward compatibility.
        /// </summary>
        /// <param name="dtView">The database table view to read from.</param>
        /// <param name="rowIndex">The row index to read at.</param>
        /// <param name="columnName">The database column name.</param>
        /// <param name="plot">The target plot to apply settings to.</param>
        /// <remarks>
        /// Uses <see cref="PlotSerializer.FromXElement"/> for deserialization.
        /// Legacy OxyPlotSettingsSerializer format is handled by the v1 Open path in the owning element,
        /// so this method only needs to support the modern format.
        /// If deserialization fails, the plot retains its default factory settings.
        /// </remarks>
        private static void DeserializePlot(DataTableView dtView, int rowIndex, string columnName, Plot plot)
        {
            if (plot == null) return;
            if (!dtView.ColumnNames.Contains(columnName)) return;

            var xml = dtView.GetCell(columnName, rowIndex).ToString();
            if (string.IsNullOrEmpty(xml)) return;

            try
            {
                // Try modern PlotSerializer format first
                PlotSerializer.FromXElement(plot, XElement.Parse(xml));
            }
            catch(Exception ex) 
            {
                Debug.WriteLine($"Could not deserialize Bayesian plot settings '{columnName}': {ex.Message}");
            }
        }

        /// <summary>
        /// Deep-copies visual properties from a source plot to a target plot.
        /// </summary>
        /// <param name="source">The source plot to copy from.</param>
        /// <param name="target">The target plot to copy to.</param>
        private static void CopyPlot(Plot source, Plot target)
        {
            if (source == null || target == null) return;
            PlotSerializer.FromXElement(target, PlotSerializer.ToXElement(source));
        }

